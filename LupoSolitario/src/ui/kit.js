export const esc = (s) => String(s ?? '').replace(/[&<>"']/g, (c) => ({ '&': '&amp;', '<': '&lt;', '>': '&gt;', '"': '&quot;', "'": '&#39;' })[c]);
// Some section titles in the book data still carry emoji; the interface uses icons only.
export const noEmoji = (s) => String(s ?? '').replace(/\p{Extended_Pictographic}\uFE0F?\s*/gu, '').trim();

export const calm = typeof matchMedia === 'function' && matchMedia('(prefers-reduced-motion: reduce)').matches;

export function replay(el, cls) {
  if (!el) return;
  el.classList.remove(cls);
  void el.offsetWidth;
  el.classList.add(cls);
}

/* ---------- sound ---------- */
const prefs = {
  get: (k) => { try { return localStorage.getItem(k); } catch { return null; } },
  set: (k, v) => { try { localStorage.setItem(k, v); } catch { /* private mode: just not remembered */ } },
};
export const sound = {
  get muted() { return prefs.get('games_muted') === '1'; }, // same switch as every other game on the site
  toggle() { prefs.set('games_muted', this.muted ? '0' : '1'); return this.muted; },
};
let audio = null;
function tone(f, d = 0.12, type = 'sine', v = 0.05, to = 0, at = 0) {
  if (sound.muted || typeof window === 'undefined') return;
  try {
    audio = audio || new (window.AudioContext || window.webkitAudioContext)();
    if (audio.state === 'suspended') audio.resume();
  } catch { return; }
  const t = audio.currentTime + at, o = audio.createOscillator(), g = audio.createGain();
  o.type = type; o.frequency.setValueAtTime(f, t);
  if (to) o.frequency.exponentialRampToValueAtTime(to, t + d);
  g.gain.setValueAtTime(0.0001, t);
  g.gain.exponentialRampToValueAtTime(v, t + 0.012);
  g.gain.exponentialRampToValueAtTime(0.0001, t + d);
  o.connect(g).connect(audio.destination);
  o.start(t); o.stop(t + d + 0.05);
}
