/* ---------- the Destiny Table roll, on screen ---------- */
// Flickers random digits in `el`, slowing down, then lands on `final`. Resolves when it has landed.
export function rollDigits(el, final, ms = 900) {
  return new Promise((resolve) => {
    if (!el) { resolve(); return; }
    const land = () => { el.textContent = final; el.classList.remove('rolling'); replay(el, 'landed'); sfx.land(); resolve(); };
    if (calm) { land(); return; }
    el.classList.remove('landed');
    el.classList.add('rolling');
    const t0 = performance.now();
    let last = 0;
    (function frame(t) {
      if (t - t0 >= ms) { land(); return; }
      if (t - last > 55 + (t - t0) / 7) { last = t; el.textContent = Math.floor(Math.random() * 10); sfx.tick(); }
      requestAnimationFrame(frame);
    })(t0);
  });
}
